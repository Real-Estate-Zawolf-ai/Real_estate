"""Build the static website for Cloudflare Pages (or Vercel).

    API_BASE_URL=https://aqar-api.onrender.com python scripts/build_frontend.py

The site is plain HTML/JS with no bundler, so "building" means: lay the files out
the way ``index.html`` expects (``/assets/...``), write ``runtime-config.js`` from
environment variables, and emit security headers. Output goes to ``dist/``.

Environment (all public values - this file's output is readable in the browser):

    API_BASE_URL            required, e.g. https://aqar-api.onrender.com (no path)
    CHAT_DEFAULT_LANG       ar | en            (default ar)
    VOICE_ENABLED           true | false       (default true)
    REQUEST_TIMEOUT_MS      default 60000 (a free Render instance needs ~50 s to wake)
    SHOW_PREVIEW_INVENTORY  true | false       (default false: never show sample listings)
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app" / "frontend"


class BuildError(ValueError):
    pass


def parse_bool(value: str | None, default: bool) -> bool:
    if value is None or not value.strip():
        return default
    lowered = value.strip().lower()
    if lowered in {"1", "true", "yes", "on"}:
        return True
    if lowered in {"0", "false", "no", "off"}:
        return False
    raise BuildError(f"expected true or false, got {value!r}")


def normalize_api_base(value: str | None, *, allow_insecure: bool = False) -> str:
    """The API origin, without a trailing slash. HTTPS only (except local development)."""
    if not value or not value.strip():
        raise BuildError("API_BASE_URL is required, e.g. https://aqar-api.onrender.com")
    parsed = urlparse(value.strip())
    if parsed.scheme not in {"http", "https"} or not parsed.hostname:
        raise BuildError(f"API_BASE_URL must be an absolute http(s) URL, got {value!r}")
    if parsed.path not in {"", "/"} or parsed.query or parsed.fragment:
        raise BuildError("API_BASE_URL must be an origin only (no path, query or fragment)")
    if parsed.scheme == "http" and not (allow_insecure or parsed.hostname in {"localhost", "127.0.0.1"}):
        raise BuildError("API_BASE_URL must use https (microphone access and WebSockets need a secure origin)")
    return f"{parsed.scheme}://{parsed.netloc}"


def build_config(env: dict[str, str], api_base: str) -> dict[str, object]:
    language = (env.get("CHAT_DEFAULT_LANG") or "ar").strip().lower()
    if language not in {"ar", "en"}:
        raise BuildError("CHAT_DEFAULT_LANG must be 'ar' or 'en'")
    try:
        timeout = int(env.get("REQUEST_TIMEOUT_MS") or 60000)
    except ValueError as error:
        raise BuildError("REQUEST_TIMEOUT_MS must be a number of milliseconds") from error
    return {
        "API_BASE_URL": api_base,
        "CHAT_DEFAULT_LANG": language,
        "REQUEST_TIMEOUT_MS": max(timeout, 1000),
        "VOICE_ENABLED": parse_bool(env.get("VOICE_ENABLED"), True),
        "SHOW_PREVIEW_INVENTORY": parse_bool(env.get("SHOW_PREVIEW_INVENTORY"), False),
    }


def runtime_config_js(config: dict[str, object]) -> str:
    # json.dumps produces valid JS and escapes quotes, so no value can break out.
    body = json.dumps(config, indent=2, ensure_ascii=False).replace("</", "<\\/")
    return (
        "// Generated by scripts/build_frontend.py - do not edit. Public values only.\n"
        f"window.APP_CONFIG = {body};\n"
    )


def content_security_policy(api_base: str) -> str:
    parsed = urlparse(api_base)
    websocket = ("wss" if parsed.scheme == "https" else "ws") + "://" + parsed.netloc
    return "; ".join(
        [
            "default-src 'self'",
            "script-src 'self'",
            # Templates set style="" attributes, which need 'unsafe-inline' for styles only.
            # styles.css @imports the brand fonts from Google Fonts (CSS here, files below).
            "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
            # Listing photos come from many https hosts.
            "img-src 'self' data: https:",
            f"connect-src 'self' {api_base} {websocket}",
            "font-src 'self' data: https://fonts.gstatic.com",
            "media-src 'self' blob:",
            "object-src 'none'",
            "base-uri 'none'",
            "form-action 'self'",
        ]
    )


def headers_file(csp: str) -> str:
    return f"""# Cloudflare Pages response headers (generated by scripts/build_frontend.py)
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), geolocation=(), payment=(), microphone=(self)
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Content-Security-Policy: {csp}; frame-ancestors 'none'

# The files are not content-hashed, so keep caching short and always revalidate config.
/assets/*
  Cache-Control: public, max-age=300, must-revalidate

/assets/runtime-config.js
  Cache-Control: no-cache

/
  Cache-Control: no-cache

/index.html
  Cache-Control: no-cache
"""


def inject_csp_meta(html: str, csp: str) -> str:
    """Also deliver the CSP as a <meta> tag, so hosts that ignore _headers are covered."""
    tag = f'<meta http-equiv="Content-Security-Policy" content="{csp}" />'
    if "</title>" in html:
        return html.replace("</title>", "</title>\n    " + tag, 1)
    return html.replace("<head>", "<head>\n    " + tag, 1)


def build(out: Path, env: dict[str, str], *, allow_insecure: bool = False) -> dict[str, object]:
    api_base = normalize_api_base(env.get("API_BASE_URL"), allow_insecure=allow_insecure)
    config = build_config(env, api_base)
    csp = content_security_policy(api_base)

    # Empty the directory rather than deleting it: a dev server whose working
    # directory is dist/ would otherwise make the rebuild fail (Windows, notably).
    out.mkdir(parents=True, exist_ok=True)
    for child in out.iterdir():
        shutil.rmtree(child) if child.is_dir() else child.unlink()
    assets = out / "assets"
    # Everything under app/frontend is served as /assets/... by FastAPI; mirror that.
    shutil.copytree(SOURCE, assets, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "index.html"))
    (assets / "runtime-config.js").write_text(runtime_config_js(config), encoding="utf-8")
    (out / "index.html").write_text(inject_csp_meta((SOURCE / "index.html").read_text(encoding="utf-8"), csp), encoding="utf-8")
    (out / "_headers").write_text(headers_file(csp), encoding="utf-8")
    return config


def sample_inventory_warning(config: dict[str, object]) -> str | None:
    """Sample listings are invented. On a real (non-local) site they must be a deliberate choice."""
    host = urlparse(str(config["API_BASE_URL"])).hostname
    if config["SHOW_PREVIEW_INVENTORY"] and host not in {"localhost", "127.0.0.1"}:
        return (
            "SHOW_PREVIEW_INVENTORY=true: this site will show INVENTED sample listings to visitors "
            "(labelled 'Development preview'). Delete the SHOW_PREVIEW_INVENTORY variable in the host's "
            "dashboard to show only the live catalogue."
        )
    return None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", default=str(ROOT / "dist"), help="output directory (default: dist)")
    parser.add_argument("--allow-insecure-api", action="store_true", help="permit an http:// API origin (local testing only)")
    args = parser.parse_args()
    try:
        config = build(Path(args.out), dict(os.environ), allow_insecure=args.allow_insecure_api)
    except BuildError as error:
        sys.exit(f"Frontend build failed: {error}")
    warning = sample_inventory_warning(config)
    if warning:
        print(f"WARNING: {warning}", file=sys.stderr)
    print(f"Built {args.out}")
    for key, value in config.items():
        print(f"  {key} = {value}")


if __name__ == "__main__":
    main()
